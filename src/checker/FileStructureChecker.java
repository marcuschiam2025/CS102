package checker;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;
import java.util.stream.Stream;

import exceptions.AdditionalFileException;
import exceptions.FileStructureException;
import exceptions.FolderNameException;
import exceptions.MissingFileException;
import exceptions.MissingFolderException;
import exceptions.UnzipErrorException;
import filehandling.FileHandlings;
import fixer.UsernameResolver;

// Co-authored with Claude

public class FileStructureChecker {
    // Generated by ChatGPT; modified to be dynamic and to include folder name
    // check, file name and email check and exception handling.
    // This class checks the structure of a student's submission against a
    // reference structure.
    private static final String CORRECT_FOLDER = "correctStructure";
    private static final String STUDENT_FOLDER = "studentStructure";
    // e.g. "Q1", "Q2"
    private static final String QUESTION_FOLDER = "Q\\d+";

    public static Set<String> getStructure(Path root) throws IOException {
        try (Stream<Path> paths = Files.walk(root)) {
            return paths
                    .filter(path -> !path.equals(root))
                    .map(path -> root.relativize(path)
                            .toString()
                            .replace("\\", "/"))
                    // The api folder (exam Javadoc) and macOS .DS_Store
                    // files are not the student's work, so skip them
                    .filter(path -> !("/" + path + "/").contains("/api/")
                            && !path.endsWith(".DS_Store"))
                    .collect(Collectors.toSet());
        }
    }

    public static ArrayList<Exception> structureCheck(String rightStructure,
            String checkStructure) throws IOException {
        ArrayList<Exception> exceptions = new ArrayList<>();

        try {
            // Step 1: Unzip the correct structure
            try {
                FileHandlings.unzip(rightStructure, CORRECT_FOLDER);
            } catch (Exception exception) {
                exceptions.add(new UnzipErrorException(
                        "Unable to unzip the correct structure: "
                                + exception.getMessage()));
                return exceptions;
            }

            // Step 2: Unzip the student's submission
            try {
                // Clear the previous student's files first
                FileHandlings.deleteFolder(new File(STUDENT_FOLDER));
                FileHandlings.unzip(checkStructure, STUDENT_FOLDER);
            } catch (Exception exception) {
                exceptions.add(new UnzipErrorException(
                        "Unable to unzip the student structure: "
                                + exception.getMessage()));
                return exceptions;
            }

            // Step 3: Find the root folder of the student's submission
            Path studWork = Paths.get(STUDENT_FOLDER);
            Path root = findFirstFolder(studWork);

            if (root == null) {
                exceptions.add(new FileStructureException(
                        "No root folder found in student submission."));
                return exceptions;
            }

            // Get the expected root from the correctStructure folder
            // (e.g. "RenameToYourUsername")
            Path expectedRoot = findFirstFolder(Paths.get(CORRECT_FOLDER));

            // Step 4: Compare the structures
            // The folder must be named after the username in the ZIP name
            // (e.g. 2023-2024-fen.lai.2022.zip -> fen.lai.2022), not just look
            // like a username, or grading will not find it
            String username = UsernameResolver.getUsername(checkStructure);
            String folderName = root.getFileName().toString();
            boolean matchesZip = username == null
                    || folderName.equalsIgnoreCase(username);

            if (FolderNameChecker.isValidFolderName(root.toString())
                    && matchesZip) {
                compareStructures(expectedRoot, root, "Missing: ",
                        "Extra: ", exceptions);
                checkNamesAndEmails(studWork, exceptions);
                return exceptions;
            }

            // The folder name is wrong, so compare question by question
            exceptions.add(new FolderNameException("Folder name is incorrect"));
            checkQuestionFolders(root, expectedRoot, studWork, exceptions);
        } catch (Exception exception) {
            exceptions.add(new FileStructureException(
                    "Structure checking error: " + exception.getMessage()));
        }

        return exceptions;
    }

    // Returns the first folder inside the given folder, or null if none
    private static Path findFirstFolder(Path folder) throws IOException {
        try (Stream<Path> paths = Files.list(folder)) {
            return paths
                    .filter(Files::isDirectory)
                    .findFirst()
                    .orElse(null);
        }
    }

    // Adds an exception for files the student is missing and for files
    // the student has that are not expected
    private static void compareStructures(Path expected, Path student,
            String missingLabel, String extraLabel,
            ArrayList<Exception> exceptions) throws IOException {
        Set<String> expectedStructure = getStructure(expected);
        Set<String> studentStructure = getStructure(student);

        Set<String> missing = new HashSet<>(expectedStructure);
        missing.removeAll(studentStructure);

        Set<String> extra = new HashSet<>(studentStructure);
        extra.removeAll(expectedStructure);

        if (!missing.isEmpty()) {
            exceptions.add(new MissingFileException(missingLabel + missing));
        }

        if (!extra.isEmpty()) {
            exceptions.add(new AdditionalFileException(extraLabel + extra));
        }
    }

    // Checks name and email comments in every Java file
    private static void checkNamesAndEmails(Path studWork,
            ArrayList<Exception> exceptions) throws IOException {
        try (Stream<Path> paths = Files.walk(studWork)) {
            paths.filter(Files::isRegularFile)
                    .filter(path -> path.toString().endsWith(".java"))
                    .forEach(path -> exceptions.addAll(
                            MissingNameOrEmail.catchMissingNames(
                                    path.toString())));
        }
    }

    // Used when the root folder is wrongly named: checks each expected
    // question folder (Q1, Q2, ...) against the student's submission
    private static void checkQuestionFolders(Path root, Path expectedRoot,
            Path studWork, ArrayList<Exception> exceptions) {
        List<Path> questionFolders;

        try (Stream<Path> paths = Files.list(expectedRoot)) {
            questionFolders = paths
                    .filter(Files::isDirectory)
                    .filter(path -> path.getFileName().toString()
                            .matches(QUESTION_FOLDER))
                    .collect(Collectors.toList()); // List keeps the order
        } catch (IOException exception) {
            exceptions.add(new FileStructureException(
                    "Unable to read expected structure: "
                            + exception.getMessage()));
            return;
        }

        if (questionFolders.isEmpty()) {
            exceptions.add(new FileStructureException(
                    "No question folders found in expected structure."));
            return;
        }

        // The student root may itself be Q1/Q2/etc., or the question
        // folders may be inside the wrongly named folder
        Path questionRoot = root;
        if (root.getFileName().toString().matches(QUESTION_FOLDER)) {
            questionRoot = root.getParent();
        }

        try {
            for (Path expectedQuestion : questionFolders) {
                // e.g. "Q1"
                String questionName = expectedQuestion.getFileName()
                        .toString();
                Path studentQuestion = questionRoot.resolve(questionName);

                if (!Files.isDirectory(studentQuestion)) {
                    exceptions.add(new MissingFolderException(
                            "Missing folder: " + questionName));
                } else {
                    compareStructures(expectedQuestion, studentQuestion,
                            questionName + " missing: ",
                            questionName + " extra: ", exceptions);
                }
            }

            checkNamesAndEmails(studWork, exceptions);
        } catch (IOException exception) {
            exceptions.add(new FileStructureException(
                    "Unable to check question folders: "
                            + exception.getMessage()));
        }
    }
}
