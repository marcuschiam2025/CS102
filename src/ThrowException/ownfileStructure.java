public class ownfileStructure {
    // Generated by ChatGPT; modified to be dynamic and to include folder name
    // check, file name and email check
    // and exception handling. This class checks the structure of a student's
    // submission against a reference structure.
    // validation
    public static Set<String> getStructure(Path root)
            throws IOException {

        try (Stream<Path> paths = Files.walk(root)) {
            return paths
                    .filter(path -> !path.equals(root))
                    .map(path -> root.relativize(path)
                            .toString()
                            .replace("\\", "/"))
                    .collect(Collectors.toSet());
        }
    }

    public static ArrayList<Exception> Structurecheck(String rightStructure, String checkStructure) throws IOException {
        ArrayList<Exception> exceptions = new ArrayList<>();

        try {

            // Step 1: Unzip the correct structure
            try {
                fileHandlings.unzip(
                        rightStructure,
                        "correctStructure");
            } catch (Exception e) {
                exceptions.add(new Exception(
                        "Unable to unzip the correct structure: "
                                + e.getMessage()));
                return exceptions;
            }

            // Step 2: Unzip the student's submission
            try {
                fileHandlings.unzip(
                        checkStructure,
                        "studentStructure");
            } catch (Exception e) {
                exceptions.add(new Exception(
                        "Unable to unzip the student structure: "
                                + e.getMessage()));
                return exceptions;
            }

            Path studWork = Paths.get("studentStructure");
            Path root;

            try (Stream<Path> paths = Files.list(studWork)) {
                root = paths
                        .filter(Files::isDirectory)
                        .findFirst()
                        .orElse(null);
            }

            if (FolderNameChecker.FolderName(root.toString())) {
                System.out.println("Folder name is correct");

                // if folder name is correct, check the structure
                Path expectedRoot = Paths.get("correctStructure/RenameToYourUsername");
                Path studentRoot = root;
                Set<String> expectedStructure = ownfileStructure.getStructure(expectedRoot);
                Set<String> studentStructure = ownfileStructure.getStructure(studentRoot);

                Set<String> missing = new HashSet<>(expectedStructure);
                missing.removeAll(studentStructure);

                Set<String> extra = new HashSet<>(studentStructure);
                extra.removeAll(expectedStructure);

                if (!missing.isEmpty()) {
                    exceptions.add(new Exception("Missing: " + missing));
                }

                if (!extra.isEmpty()) {
                    exceptions.add(new Exception("Extra: " + extra));
                }

                // Check name and email comments in every Java file
                try (Stream<Path> paths = Files.walk(studWork)) {

                    paths.filter(Files::isRegularFile)
                            .filter(path -> path.toString().endsWith(".java"))
                            .forEach(path -> {

                                // Check whether this Java file has name and email comments
                                ArrayList<Exception> nameErrors = MissingNameOrEmail.catchMissingNames(path.toString());

                                // Add all errors to the main exceptions list
                                exceptions.addAll(nameErrors);
                            });

                }

            } else {
                exceptions.add(new Exception("Folder name is incorrect"));

                Path expectedRoot = Paths.get("correctStructure/RenameToYourUsername");

                // Check whether the student root itself contains Q1, Q2, etc.
                // or whether those folders are inside the wrongly named folder.
                Path questionRoot = root;

                try (Stream<Path> paths = Files.list(expectedRoot)) {
                    boolean expectedHasQuestions = paths
                            .filter(Files::isDirectory)
                            .anyMatch(p -> p.getFileName().toString()
                                    .matches("Q\\d+"));

                    if (!expectedHasQuestions) {
                        exceptions.add(new Exception(
                                "No question folders found in expected structure."));
                        return exceptions;
                    }
                } catch (IOException e) {
                    exceptions.add(new Exception(
                            "Unable to read expected structure: " + e.getMessage()));
                    return exceptions;
                }

                // If root itself is Q1/Q2/etc., use its parent
                if (root.getFileName().toString().matches("Q\\d+")) {
                    questionRoot = root.getParent();
                }

                try (Stream<Path> paths = Files.list(expectedRoot)) {
                    List<Path> questionFolders = paths
                            .filter(Files::isDirectory)
                            .filter(p -> p.getFileName().toString()
                                    .matches("Q\\d+"))
                            .collect(Collectors.toList());

                    for (Path expectedQuestion : questionFolders) {
                        String questionName = expectedQuestion.getFileName().toString();

                        Path studentQuestion = questionRoot.resolve(questionName);

                        if (!Files.isDirectory(studentQuestion)) {
                            exceptions.add(new Exception(
                                    "Missing folder: " + questionName));
                            continue;
                        }

                        Set<String> expectedStructure = ownfileStructure.getStructure(expectedQuestion);

                        Set<String> studentStructure = ownfileStructure.getStructure(studentQuestion);

                        Set<String> missing = new HashSet<>(expectedStructure);
                        missing.removeAll(studentStructure);

                        Set<String> extra = new HashSet<>(studentStructure);
                        extra.removeAll(expectedStructure);

                        if (!missing.isEmpty()) {
                            exceptions.add(new Exception(
                                    questionName + " missing: " + missing));
                        }

                        if (!extra.isEmpty()) {
                            exceptions.add(new Exception(
                                    questionName + " extra: " + extra));
                        }
                    }
                    // Check name and email comments in every Java file
                    try (Stream<Path> javaFilesPaths = Files.walk(studWork)) {

                        javaFilesPaths.filter(Files::isRegularFile)
                                .filter(path -> path.toString().endsWith(".java"))
                                .forEach(path -> {

                                    // Check whether this Java file has name and email comments
                                    ArrayList<Exception> nameErrors = MissingNameOrEmail
                                            .catchMissingNames(path.toString());

                                    // Add all errors to the main exceptions list
                                    exceptions.addAll(nameErrors);
                                });

                    }
                } catch (IOException e) {
                    exceptions.add(new Exception(
                            "Unable to check question folders: " + e.getMessage()));
                }
            }

        } catch (Exception e) {
            exceptions.add(new Exception(
                    "Structure checking error: " + e.getMessage()));
        } finally {
            deleteFolder(Paths.get("correctStructure"));
            deleteFolder(Paths.get("studentStructure"));
        }
        return exceptions;
    }

    public static void deleteFolder(Path folder) throws IOException {
        if (!Files.exists(folder)) {
            return;
        }

        try (Stream<Path> paths = Files.walk(folder)) {
            paths.sorted(Comparator.reverseOrder())
                    .forEach(path -> {
                        try {
                            Files.delete(path);
                        } catch (IOException e) {
                            throw new RuntimeException(e);
                        }
                    });
        }
    }

    public static void main(String[] args) {

        String rightStructure = "../RenameToYourUsername.zip";

        // Folder containing all students' ZIP submissions
        File studentFolder = new File("../student-submission");

        // Get all files inside the folder
        File[] studentFiles = studentFolder.listFiles();

        if (studentFiles == null) {
            System.out.println("Unable to find student-submission folder.");
            System.out.println("Working directory: "
                    + System.getProperty("user.dir"));
            return;
        }

        int totalStudents = 0;
        int passedStudents = 0;
        int failedStudents = 0;

        // Loop through every file
        for (File studentZip : studentFiles) {

            // Only process ZIP files
            if (studentZip.isFile() &&
                    studentZip.getName().toLowerCase().endsWith(".zip")) {

                totalStudents++;

                System.out.println("\n================================");
                System.out.println("Checking student: " + studentZip.getName());
                System.out.println("================================");

                try {
                    ArrayList<Exception> exceptions = Structurecheck(
                            rightStructure,
                            studentZip.getPath());

                    if (exceptions.isEmpty()) {
                        passedStudents++;
                        System.out.println("No exceptions found!");
                    } else {
                        failedStudents++;
                        System.out.println("Exceptions found:");

                        for (Exception e : exceptions) {
                            System.out.println("- " + e.getMessage());
                        }
                    }

                } catch (IOException e) {
                    failedStudents++;
                    System.err.println(
                            "Error checking " + studentZip.getName()
                                    + ": " + e.getMessage());
                }
            }
        }

        // Display overall results
        System.out.println("\n========== SUMMARY ==========");
        System.out.println("Total students checked: " + totalStudents);
        System.out.println("Passed: " + passedStudents);
        System.out.println("Failed: " + failedStudents);
    }

}